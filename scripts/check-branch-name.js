#!/usr/bin/env node
/**
 * Branch-name gate for the convention in docs/REPOSITORY_PROCEDURES.md §1.
 *
 * It exists because the convention was written down three times, in three incompatible
 * versions, and none of them matched what anyone was actually doing — a branch drifted 47
 * commits behind main while still being named in CLAUDE.md as the place all work goes. Hygiene
 * rule 4: a checker nothing runs is not a checker, so this runs inside `npm run hygiene`.
 *
 * Deliberately permissive about WHERE it refuses to run. A gate that fails on every Dependabot
 * PR gets muted, and a muted gate catches nothing:
 *
 *   - `main` passes. It is the trunk, not a working branch.
 *   - `dependabot/**` passes. Those names are generated and not ours to choose.
 *   - `claude/<id>` passes for the same reason: the Claude Code session tool assigns it, and a
 *     session is told to use it. The discipline that matters — one change per PR, restart from
 *     `origin/main` once that PR merges — is a rule about history, which a name cannot show.
 *   - Detached HEAD passes. CI checks out a merge ref, so there is no branch to judge; a
 *     failure here would only mean "you are in CI", which is not a defect.
 *
 * Override with ALLOW_ANY_BRANCH_NAME=true for a deliberate one-off. It prints the waiver, so
 * the escape hatch cannot be used quietly.
 */

const { execFileSync } = require("child_process");

/** Prefixes a human or an agent chooses. `<desc>` is kebab-case, at least two characters. */
const CONVENTION = [
  { pattern: /^feat\/[a-z0-9][a-z0-9-]*[a-z0-9]$/, label: "feat/<desc>", for: "new capability" },
  { pattern: /^fix\/[a-z0-9][a-z0-9-]*[a-z0-9]$/, label: "fix/<desc>", for: "bug fix" },
  {
    pattern: /^chore\/[a-z0-9][a-z0-9-]*[a-z0-9]$/,
    label: "chore/<desc>",
    for: "maintenance, CI, docs, deps",
  },
  {
    pattern: /^hotfix\/[a-z0-9][a-z0-9-]*[a-z0-9]$/,
    label: "hotfix/<desc>",
    for: "critical patch on live code",
  },
];

/** Names nobody chose, so nobody can get them wrong. */
const GENERATED = [
  { pattern: /^main$/, why: "the trunk" },
  { pattern: /^release\/v\d+\.\d+\.\d+$/, why: "generated by release.yml" },
  { pattern: /^dependabot\//, why: "generated by Dependabot" },
  {
    pattern: /^claude\/[A-Za-z0-9][A-Za-z0-9._-]*$/,
    why: "assigned by the Claude Code session tool",
  },
];

function currentBranch() {
  try {
    return execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

function main() {
  const branch = currentBranch();

  if (!branch) {
    console.log("[branch-name] no git branch resolved — skipping");
    return 0;
  }

  // CI checks out a merge commit, so HEAD is detached and there is no branch to judge.
  if (branch === "HEAD") {
    console.log("[branch-name] detached HEAD (CI checks out a merge ref) — skipping");
    return 0;
  }

  const generated = GENERATED.find((g) => g.pattern.test(branch));
  if (generated) {
    console.log(`[branch-name] ${branch} — ${generated.why}, not checked`);
    return 0;
  }

  if (CONVENTION.some((c) => c.pattern.test(branch))) {
    console.log(`[branch-name] ${branch} — OK`);
    return 0;
  }

  if (process.env.ALLOW_ANY_BRANCH_NAME === "true") {
    console.warn(
      `[branch-name] ${branch} does not match the convention, waived by ALLOW_ANY_BRANCH_NAME.`,
    );
    return 0;
  }

  console.error(`\n[branch-name] "${branch}" does not match the convention.\n`);
  for (const c of CONVENTION) {
    console.error(`  ${c.label.padEnd(16)} ${c.for}`);
  }
  console.error(`
One change per PR: branch from origin/main, open one PR, and delete the branch once it merges.
A branch that outlives its PR accumulates unrelated work nobody can review as a unit.

  git fetch origin main
  git checkout -B fix/short-description origin/main

Full rules: docs/REPOSITORY_PROCEDURES.md §1.
Deliberate exception: ALLOW_ANY_BRANCH_NAME=true (it says so in the output).
`);
  return 1;
}

process.exit(main());
